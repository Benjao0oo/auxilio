def encontrar_fila_header(
    path,
    sheet_name,
    palabras_clave,
    max_rows=12
):

    preview = pd.read_excel(
        path,
        sheet_name=sheet_name,
        header=None,
        nrows=max_rows
    )

    for i in range(len(preview)):

        fila = " ".join(
            str(x).strip().lower()
            for x in preview.iloc[i].tolist()
            if pd.notna(x)
        )

        coincidencias = sum(
            palabra.lower() in fila
            for palabra in palabras_clave
        )

        if coincidencias >= 1:
            return i

    return 0


