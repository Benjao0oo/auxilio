    temp = df_analiticos.copy()

    temp["_metrica"] = (
        temp[col_metrica]
        .astype(str)
        .str.strip()
        .str.lower()
    )

    for nombre in nombres:

        mask = (
            temp["_metrica"]
            ==
            nombre.lower()
        )

        if mask.any():

            return numero(
                temp.loc[
                    mask,
                    col_valor
                ].iloc[0]
            )

    return None


