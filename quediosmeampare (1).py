def numero_brand24(valor):
    """
    Convierte valores de Brand24 como:

        457K
        7.7 K
        3.7 M
        28 B
        166
        $53K
        9/100

    a valores numéricos aproximados.
    """

    if pd.isna(valor):
        return np.nan

    s = str(valor).strip()

    # Eliminar $
    s = s.replace("$", "")

    # Presence Score
    if "/" in s:
        try:
            return float(s.split("/")[0])
        except:
            return np.nan

    # Normalizar espacios
    s = s.replace(" ", "")

    # Porcentaje
    if "%" in s:
        try:
            return float(
                s.replace("%", "")
            )
        except:
            return np.nan

    # Multiplicadores Brand24
    multiplicador = 1

    if s.upper().endswith("K"):
        multiplicador = 1_000
        s = s[:-1]

    elif s.upper().endswith("M"):
        multiplicador = 1_000_000
        s = s[:-1]

    elif s.upper().endswith("B"):
        multiplicador = 1_000_000_000
        s = s[:-1]

    try:

        return float(
            s.replace(",", "")
        ) * multiplicador

    except:

        try:

            limpio = re.sub(
                r"[^\d.\-]",
                "",
                s
            )

            return float(limpio)

        except:

            return np.nan


def formato_numero(valor):
    """
    Formato amigable para mostrar números.
    """

    if pd.isna(valor):
        return "N/D"

    valor = float(valor)

    if abs(valor) >= 1_000_000_000:
        return f"{valor/1_000_000_000:.1f} B"

    if abs(valor) >= 1_000_000:
        return f"{valor/1_000_000:.1f} M"

    if abs(valor) >= 1_000:
        return f"{valor/1_000:.1f} K"

    return f"{valor:,.0f}"


