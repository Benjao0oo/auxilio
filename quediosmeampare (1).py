def limpiar_dataframe_numerico(df, columna):
    """
    Crea una columna numérica segura.
    """

    df = df.copy()

    df[f"{columna}_num"] = df[columna].apply(
        numero_brand24
    )

    df = df.replace(
        [np.inf, -np.inf],
        np.nan
    )

    df = df.dropna(
        subset=[f"{columna}_num"]
    )

    return df


