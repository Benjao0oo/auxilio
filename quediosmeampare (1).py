def format_value(
    value,
    name
):

    value = numero(value)

    if name == "AVE":

        if value >= 1_000_000:

            return (
                f"${value / 1_000_000:.1f}M"
            )

        elif value >= 1_000:

            return (
                f"${value / 1_000:.1f}K"
            )

        else:

            return f"${value:,.0f}"


    if "Alcance" in name:

        if value >= 1_000_000:

            return (
                f"{value / 1_000_000:.1f}M"
            )

        elif value >= 1_000:

            return (
                f"{value / 1_000:.1f}K"
            )


    return (
        f"{value:,.0f}"
        .replace(",", ".")
    )


