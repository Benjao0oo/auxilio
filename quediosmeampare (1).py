def buscar_columna(
    df,
    candidatos
):

    if df.empty:
        return None

    columnas = list(df.columns)

    # Coincidencia exacta
    for candidato in candidatos:

        for col in columnas:

            if (
                str(col)
                .strip()
                .lower()
                ==
                candidato.lower()
            ):

                return col

    # Coincidencia parcial
    for candidato in candidatos:

        candidato = candidato.lower()

        for col in columnas:

            if candidato in str(col).lower():

                return col

    return None


def numero(valor):

    if pd.isna(valor):
        return 0

    if isinstance(valor, str):

        valor = (
            valor
            .replace("%", "")
            .replace("$", "")
            .replace(",", "")
            .strip()
        )

    try:
        return float(valor)

    except:

        return 0


